"""Seeded SYNTHETIC fault-history generator (`make seed`).

Fixed seed => identical files every run. ~10 machines, ~300 records, including
deliberately ambiguous and incomplete records. Every file carries a SYNTHETIC label.
"""
from __future__ import annotations

import json
import random
from datetime import date, timedelta
from pathlib import Path

from app.data_gen.catalog import FAULT_CODES

SEED = 42
N_MACHINES = 10
N_RECORDS = 300
LABEL = "SYNTHETIC - generated by app/data_gen/faults_gen.py (seed 42). Not real plant data."

SITES = ["Cooling water loop", "Boiler feed", "Process transfer", "Effluent transfer", "Raw water intake"]

DETAILS = {
    "PF-101": lambda r: f", {r.uniform(5.0, 11.0):.1f} mm/s at the drive-end bearing housing",
    "PF-102": lambda r: f", bearing housing at {r.randint(82, 98)} C",
    "PF-103": lambda r: f", about {r.randint(12, 60)} drops per minute",
    "PF-104": lambda r: f", suction pressure down to {r.uniform(0.2, 0.8):.1f} bar",
    "PF-105": lambda r: f", discharge pressure {r.uniform(2.5, 3.6):.1f} bar against 4.4 bar expected",
    "PF-106": lambda r: f", current {r.randint(31, 38)} A against 28 A rated",
    "PF-107": lambda r: ", discharge flow zero",
    "PF-108": lambda r: f", discharge pressure {r.uniform(5.4, 6.5):.1f} bar",
    "PF-109": lambda r: ", motor tripped on winding thermistor",
    "PF-110": lambda r: ", rhythmic knock at running speed",
    "PF-111": lambda r: ", screen shows signal out of range",
    "PF-112": lambda r: ", noise louder at the pump end",
}

VAGUE = [
    "pump sounded odd during the shift, went away on its own",
    "operator says something is not right with the pump",
    "intermittent issue reported, could not reproduce",
    "pump behaving strangely since the weekend",
    "noise reported by night shift, no details",
]


def generate(seed: int = SEED) -> tuple[list[dict], list[dict]]:
    rng = random.Random(seed)
    machines = []
    for i in range(1, N_MACHINES + 1):
        machines.append({
            "machine_id": f"CP-{i:02d}",
            "model": "FF-CP150 (SYNTHETIC)",
            "service": SITES[(i - 1) % len(SITES)],
            "installed": (date(2015, 1, 1) + timedelta(days=rng.randint(0, 3000))).isoformat(),
            "synthetic": True,
        })
    start = date(2024, 1, 1)
    records = []
    for n in range(1, N_RECORDS + 1):
        m = rng.choice(machines)["machine_id"]
        day = (start + timedelta(days=rng.randint(0, 900))).isoformat()
        roll = rng.random()
        if roll < 0.08:  # ambiguous: vague symptom, no code, no root cause
            rec = {"symptom": f"{m}: {rng.choice(VAGUE)}", "fault_code": None, "root_cause": "undetermined",
                   "fix": "No fault found, monitored", "downtime_hours": round(rng.uniform(0, 1.5), 1),
                   "notes": "AMBIGUOUS record (SYNTHETIC)"}
        else:
            fc = rng.choice(FAULT_CODES)
            cause = rng.choices(fc.causes, weights=[c.weight for c in fc.causes])[0]
            symptom = f"{m}: {rng.choice(fc.symptoms)}{DETAILS[fc.code](rng)}"
            if rng.random() < 0.5:
                symptom += f", controller showed {fc.code}"
            rec = {"symptom": symptom, "fault_code": fc.code, "root_cause": cause.category, "fix": cause.fix,
                   "downtime_hours": round(rng.uniform(0.5, 16.0), 1), "notes": None}
            if roll > 0.95:  # incomplete: fix or downtime missing
                if rng.random() < 0.5:
                    rec["fix"] = None
                else:
                    rec["downtime_hours"] = None
                rec["notes"] = "INCOMPLETE record (SYNTHETIC)"
        records.append({"record_id": f"FR-{n:04d}", "date": day, "machine_id": m, **rec})
    records.sort(key=lambda r: r["record_id"])
    return machines, records


def write_files(folder: Path, seed: int = SEED) -> tuple[list[dict], list[dict]]:
    machines, records = generate(seed)
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "SYNTHETIC_machines.json").write_text(
        json.dumps({"label": LABEL, "machines": machines}, indent=1), encoding="utf-8")
    (folder / "SYNTHETIC_fault_records.json").write_text(
        json.dumps({"label": LABEL, "records": records}, indent=1), encoding="utf-8")
    return machines, records


def seed_store(settings, store) -> dict:
    from app.llm import get_embedder
    from app.store.base import fault_search_text

    known = {c["code"] for c in store.list_fault_codes()}
    machines, records = write_files(settings.synthetic_dir)
    missing = {r["fault_code"] for r in records if r["fault_code"]} - known
    embeddings = get_embedder(settings).embed([fault_search_text(r) for r in records])
    store.replace_fault_data(machines, records, embeddings)
    return {"machines": len(machines), "records": len(records),
            "codes_not_in_manual": sorted(missing),
            "ambiguous": sum(1 for r in records if r["root_cause"] == "undetermined"),
            "incomplete": sum(1 for r in records if (r["notes"] or "").startswith("INCOMPLETE"))}
